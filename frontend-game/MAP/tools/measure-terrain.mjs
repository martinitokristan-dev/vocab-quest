// Measurement aid (QA/authoring only, not shipped): measures the GEOMETRY of the reference on an 18x10 cell grid
// (water, stone bank and cobble plaza cells) and writes MAP/data/scenes/k1-terrain.ts as plain ASCII data.
// No colour information is stored; the runtime never loads the reference.
//   node MAP/tools/measure-terrain.mjs
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ref = path.resolve('MAP/reference/vocab-quest-map.png');
const b = await chromium.launch({ channel: 'msedge', headless: true });
const page = await (await b.newContext()).newPage();
await page.goto(pathToFileURL(ref).href);
const res = await page.evaluate(() => {
  const img = document.querySelector('img');
  const c = document.createElement('canvas');
  c.width = img.naturalWidth;
  c.height = img.naturalHeight;
  const g = c.getContext('2d');
  g.drawImage(img, 0, 0);
  const W = c.width;
  const H = c.height;
  const d = g.getImageData(0, 0, W, H).data;
  // landmark regions where tan/cream wall pixels must not become path cells
  const skip = [
    [80, 300, 460, 510],
    [725, 262, 1085, 478],
    [1325, 90, 1755, 335],
    [28, 525, 402, 735],
    [640, 395, 735, 495],
    [1258, 262, 1346, 340],
    [1608, 330, 1766, 405],
  ];
  const cells = [];
  for (let rj = 0; rj * 10 < H; rj++) {
    const row = [];
    for (let gi = 0; gi * 18 < W; gi++) {
      let water = 0;
      let stone = 0;
      let path = 0;
      let n = 0;
      let R = 0;
      let G = 0;
      let B = 0;
      for (let y = rj * 10; y < Math.min(H, rj * 10 + 10); y++) {
        for (let x = gi * 18; x < Math.min(W, gi * 18 + 18); x++) {
          const i = (y * W + x) * 4;
          const r = d[i];
          const gg = d[i + 1];
          const bl = d[i + 2];
          n++;
          R += r;
          G += gg;
          B += bl;
          if (y >= 195 && bl > r * 1.3 && bl > gg * 1.02 && bl > 105) water++;
          const mx = Math.max(r, gg, bl);
          const mn = Math.min(r, gg, bl);
          if (mx - mn < 26 && mx > 85 && mx < 205) stone++;
          if (r > 165 && gg > 140 && bl > 80 && bl < 190 && r - bl > 30 && gg > r * 0.8) path++;
        }
      }
      const cx = gi * 18 + 9;
      const cy = rj * 10 + 5;
      const inSkip = skip.some(([x0, y0, x1, y1]) => cx >= x0 && cx <= x1 && cy >= y0 && cy <= y1);
      let ch = '.';
      if (cy >= 195 && water / n >= 0.14) ch = 'w';
      else if (!inSkip && cy >= 195 && path / n >= 0.4) ch = 'p';
      else if (!inSkip && cy >= 195 && stone / n >= 0.45) ch = 's';
      row.push({ ch });
    }
    cells.push(row);
  }
  return cells;
});
await b.close();

const rows = res.map((row) => row.map((c) => c.ch).join(''));
const body = rows.map((r) => `  '${r}',`).join('\n');
writeFileSync(
  path.resolve('MAP/data/scenes/k1-terrain.ts'),
  `/**
 * K1 S1 measured terrain geometry, one char per 18x10 reference cell (row = refY / 10, column = refX / 18):
 * 'w' water, 's' stone bank, 'p' cobble plaza, '.' ground. Generated by tools/measure-terrain.mjs, editable by hand.
 */
export const K1_TERRAIN: readonly string[] = [
${body}
];
`,
);
