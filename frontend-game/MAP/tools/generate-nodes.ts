import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { computeLayout } from '../src/core/layout';
import type { NodeRecord } from '../src/api/types';
import type { EntranceRecord, GateRecord } from '../data/world';

const HEADER = '// GENERATED by MAP/tools/generate-nodes.ts. Do not edit; run `npm run map:nodes` to regenerate.\n';

function nodeLine(n: NodeRecord): string {
  const parts = [
    `kingdom: ${n.kingdom}`,
    `level: ${n.level}`,
    `globalIndex: ${n.globalIndex}`,
    `x: ${n.x}`,
    `y: ${n.y}`,
    `blockH: ${n.blockH}`,
    `segment: ${n.segment}`,
  ];
  if (n.hop) parts.push(`hop: '${n.hop}'`);
  if (n.station) parts.push(`station: ${JSON.stringify(n.station)}`);
  return `  { ${parts.join(', ')} },`;
}

export function buildNodesSource(): string {
  const { nodes } = computeLayout();
  return (
    HEADER +
    "import type { NodeRecord } from '../src/api/types';\n\n" +
    'export const NODES: readonly NodeRecord[] = [\n' +
    nodes.map(nodeLine).join('\n') +
    '\n];\n'
  );
}

function gateLine(g: GateRecord): string {
  return (
    `  { kingdom: ${g.kingdom}, archX: ${g.archX}, archY: ${g.archY}, frontX: ${g.frontX}, frontY: ${g.frontY}, ` +
    `nextSpawnX: ${g.nextSpawnX}, nextSpawnY: ${g.nextSpawnY} },`
  );
}

function entranceLine(e: EntranceRecord): string {
  return (
    `  { kingdom: ${e.kingdom}, hit: { x: ${e.hit.x}, y: ${e.hit.y}, w: ${e.hit.w}, h: ${e.hit.h} }, ` +
    `spawnX: ${e.spawnX}, spawnY: ${e.spawnY} },`
  );
}

export function buildGatesSource(): string {
  const { gates, entrances } = computeLayout();
  return (
    HEADER +
    "import type { EntranceRecord, GateRecord } from './world';\n\n" +
    'export const GATES: readonly GateRecord[] = [\n' +
    gates.map(gateLine).join('\n') +
    '\n];\n\n' +
    'export const ENTRANCES: readonly EntranceRecord[] = [\n' +
    entrances.map(entranceLine).join('\n') +
    '\n];\n'
  );
}

export function dataDir(): string {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'data');
}

export function writeGenerated(): void {
  writeFileSync(path.join(dataDir(), 'nodes.ts'), buildNodesSource());
  writeFileSync(path.join(dataDir(), 'gates.ts'), buildGatesSource());
}
